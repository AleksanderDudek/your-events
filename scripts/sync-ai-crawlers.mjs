#!/usr/bin/env node
// Refreshes src/config/aiCrawlers.generated.ts from the community-maintained
// list at github.com/ai-robots-txt/ai.robots.txt — AI training crawlers, AI
// search/answer engines and AI agents, tracked as vendors announce them.
//
//   node scripts/sync-ai-crawlers.mjs
//
// Then review the diff (new names are usually fine; a name that is really a
// search engine or a link-preview bot belongs in KEEP_ALLOWED below), run
// `pnpm test src/lib/robotsTxt.spec.ts` and commit.
//
// Not run in CI on purpose: a build must never change because a third-party
// list changed overnight.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const SOURCE = 'https://raw.githubusercontent.com/ai-robots-txt/ai.robots.txt/main/robots.txt';
const COMMITS = 'https://api.github.com/repos/ai-robots-txt/ai.robots.txt/commits/main';
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'config', 'aiCrawlers.generated.ts');

// On the upstream list, but they must keep reaching the site:
// - Applebot is Apple's SEARCH crawler (Spotlight, Siri, Safari suggestions);
//   AI training is Applebot-Extended, which stays blocked.
// - facebookexternalhit builds the link preview when a plan or an event is
//   pasted into Messenger or Facebook. Blocking it turns every shared link
//   into a bare URL.
const KEEP_ALLOWED = new Set(['applebot', 'facebookexternalhit']);

// Tokens so generic that a sloppy robots.txt parser could match them inside an
// unrelated crawler's name (`Spider` in `Baiduspider`, `Dot` in `DotBot`).
const AMBIGUOUS = new Set(['code', 'cursor', 'dot', 'instinct', 'lcc', 'muse', 'openai', 'spider', 'trae', 'yak']);

function parse(robotsTxt) {
  const seen = new Set();
  const names = [];
  for (const line of robotsTxt.split('\n')) {
    const match = line.match(/^user-agent:\s*(.+?)\s*$/i);
    if (!match) continue;
    const name = match[1];
    const key = name.toLowerCase();
    // `__usage_ai-training` is an upstream marker, not a crawler; `iaskspider/2.0`
    // and `Brightbot 1.0` are versioned duplicates of a name already listed.
    if (name.startsWith('__') || name.includes('/') || /\s\d/.test(name)) continue;
    if (KEEP_ALLOWED.has(key) || AMBIGUOUS.has(key) || seen.has(key)) continue;
    seen.add(key);
    names.push(name);
  }
  return names.sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }));
}

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE}: HTTP ${response.status}`);
const names = parse(await response.text());
if (names.length < 50) throw new Error(`Only ${names.length} crawlers parsed — upstream format changed?`);

let revision = 'unknown';
try {
  const commit = await (await fetch(COMMITS)).json();
  revision = `${commit.sha.slice(0, 12)} (${commit.commit.committer.date.slice(0, 10)})`;
} catch {
  // The revision is a note for the reader; the list itself is what matters.
}

const body = `// GENERATED by scripts/sync-ai-crawlers.mjs — do not edit by hand.
// Source: ai-robots-txt/ai.robots.txt @ ${revision}
// Exclusions (search and link-preview bots, ambiguous tokens) live in the script.

export const AI_CRAWLERS: readonly string[] = [
${names.map((n) => `  '${n.replace(/[\\']/g, '\\$&')}',`).join('\n')}
];
`;
writeFileSync(OUT, body);
console.log(`${names.length} AI crawlers written to ${OUT}`);
